"""Evidence bundle generated from artifacts — never from hardcoded pass flags.

Every requirement stores the values that were compared and the path to the
supporting artifact. `passed` is computed from those values.
"""

from __future__ import annotations

import json
from pathlib import Path


def _row(req: str, passed: bool, evidence: str, values: dict) -> dict:
    return {
        "requirement": req,
        "result": "PASS" if passed else "FAIL",
        "passed": bool(passed),
        "evidence": evidence,
        "values": values,
    }


def write_evidence(out_dir: Path, rows: list[dict], extra: dict | None = None) -> None:
    payload = {
        "schema": "helix-evidence-v1",
        "all_passed": all(r["passed"] for r in rows),
        "requirements": rows,
        "extra": extra or {},
    }
    (out_dir / "evidence.json").write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
    lines = [
        "# Helix evidence summary",
        "",
        "Generated by the implementation from `submission_artifacts/`. Hardcoded evidence is not accepted.",
        "",
        "| Requirement | Result | Evidence |",
        "|---|---|---|",
    ]
    pretty = {
        "tokenizer_integrity": "Tokenizer integrity",
        "evaluation_firewall": "Evaluation firewall",
        "packing_correctness": "Packing correctness",
        "mixture_compliance": "Mixture compliance",
        "opus_audit_trail": "OPUS audit trail",
        "crash_recovery": "Crash recovery",
        "replay": "Replay",
        "learning_trace": "Learning trace",
        "throughput": "Throughput",
    }
    for r in rows:
        name = pretty.get(r["requirement"], r["requirement"])
        lines.append(f"| {name} | {r['result']} | {r['evidence']} |")
    lines.append("")
    lines.append(f"Overall: **{'PASS' if payload['all_passed'] else 'FAIL'}**")
    (out_dir / "evidence.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def load_jsonl(path: Path) -> list[dict]:
    if not path.exists():
        return []
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]
